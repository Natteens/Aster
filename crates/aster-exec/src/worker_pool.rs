//! Worker pool that runs Aster MIR functions concurrently.
//!
//! All workers of a pool share one finalized, read-only [`ExecutableProgram`]
//! obtained from the injected [`CodeProvider`] (or adopted from the caller).
//! Every task still gets a brand new `aster_runtime::ExecutionContext` inside
//! the program's `run_*` hooks, so tasks never share arenas even when run back
//! to back on the same worker. The pool never names a concrete code generator.

use std::collections::VecDeque;
use std::sync::atomic::{AtomicU8, AtomicU64, AtomicUsize, Ordering};
use std::sync::{Arc, Condvar, Mutex, mpsc};
use std::thread::{self, JoinHandle};

use crate::completion_queue::{CompletionQueue, CompletionToken};
use crate::{BackendError, CodeProvider, ExecutableProgram, ExecutionValue, mir};

/// Internal task identity, for diagnostics only. Generated by the pool that
/// accepted the task; never reused across pools.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct TaskId(u64);

/// The owned result of one plain or awaited task, delivered over its own channel.
#[derive(Clone, Debug, PartialEq)]
pub enum TaskOutcome {
    Completed(ExecutionValue, aster_runtime::MemoryStats),
    Failed(BackendError),
}

const TASK_PENDING: u8 = 0;
const TASK_RUNNING: u8 = 1;
const TASK_CANCEL_REQUESTED: u8 = 2;
const TASK_COMPLETED: u8 = 3;
const TASK_FAILED: u8 = 4;
const TASK_CANCELLED: u8 = 5;

/// Host-owned argument bytes copied synchronously before Task.Run returns.
/// Word storage supplies the maximum ABI alignment used by current ASTER
/// finite value layouts; workers never retain caller memory.
#[derive(Clone, Debug, Default)]
pub struct TaskPayload {
    words: Vec<u64>,
    /// Arguments that cross by deep copy (CONC-005): serialized in the
    /// caller's context, materialized into the frame on the worker.
    transfers: Vec<aster_runtime::TransferItem>,
}

impl TaskPayload {
    pub(crate) fn copy_from(pointer: *const u8, size: usize) -> Result<Self, BackendError> {
        if size == 0 {
            return Ok(Self::default());
        }
        if pointer.is_null()
            || !size.is_multiple_of(8)
            || !(pointer as usize).is_multiple_of(std::mem::align_of::<u64>())
        {
            return Err(BackendError::new(
                "Task.Run received an invalid argument frame",
            ));
        }
        let words = size / 8;
        let mut owned = Vec::new();
        owned
            .try_reserve_exact(words)
            .map_err(|_| BackendError::new("Task.Run could not allocate its argument payload"))?;
        owned.resize(words, 0);
        // SAFETY: generated code passes a live stack frame of exactly `size`
        // bytes and this function copies it before returning to generated code.
        #[allow(unsafe_code)]
        unsafe {
            std::ptr::copy_nonoverlapping(pointer, owned.as_mut_ptr().cast::<u8>(), size);
        }
        Ok(Self {
            words: owned,
            transfers: Vec::new(),
        })
    }

    /// Attach the deep-copy arguments packed for this call.
    pub(crate) fn with_transfers(mut self, transfers: Vec<aster_runtime::TransferItem>) -> Self {
        self.transfers = transfers;
        self
    }

    /// Deep-copy arguments to materialize into a worker-local frame copy.
    pub fn transfers(&self) -> &[aster_runtime::TransferItem] {
        &self.transfers
    }

    /// The frame words, for building a mutable worker-local copy.
    pub fn words(&self) -> &[u64] {
        &self.words
    }

    pub fn as_ptr(&self) -> *const u64 {
        self.words.as_ptr()
    }

    pub fn is_empty(&self) -> bool {
        self.words.is_empty()
    }
}

/// Race-safe terminal state plus the backend-neutral cancellation flag read
/// by the worker's `ExecutionContext`. Plain tasks keep this record alive in
/// both the caller handle and queued/running job until the result is sent;
/// async tasks keep it in their host-owned `AsyncTask` entry. A fresh context
/// receives only an `Arc` clone of the opaque flag, never an ASTER pointer.
pub struct TaskControl {
    state: AtomicU8,
    cancellation: Arc<aster_runtime::TaskCancellation>,
}

impl Default for TaskControl {
    fn default() -> Self {
        Self::new()
    }
}

impl TaskControl {
    pub fn new() -> Self {
        Self {
            state: AtomicU8::new(TASK_PENDING),
            cancellation: Arc::new(aster_runtime::TaskCancellation::default()),
        }
    }

    pub fn cancellation(&self) -> Arc<aster_runtime::TaskCancellation> {
        Arc::clone(&self.cancellation)
    }

    pub fn cancel(&self) -> bool {
        // The successful CAS is Cancel's linearization point. A completion
        // that publishes a terminal state first makes this return false; a
        // request that wins first forces a normal completion to Cancelled.
        loop {
            let state = self.state.load(Ordering::Acquire);
            if !matches!(state, TASK_PENDING | TASK_RUNNING) {
                return false;
            }
            if self
                .state
                .compare_exchange(
                    state,
                    TASK_CANCEL_REQUESTED,
                    Ordering::AcqRel,
                    Ordering::Acquire,
                )
                .is_ok()
            {
                let _ = self.cancellation.request();
                return true;
            }
        }
    }

    pub fn begin_or_resume(&self) -> bool {
        loop {
            match self.state.load(Ordering::Acquire) {
                TASK_PENDING => {
                    if self
                        .state
                        .compare_exchange(
                            TASK_PENDING,
                            TASK_RUNNING,
                            Ordering::AcqRel,
                            Ordering::Acquire,
                        )
                        .is_ok()
                    {
                        return true;
                    }
                }
                TASK_CANCEL_REQUESTED => {
                    let _ = self.state.compare_exchange(
                        TASK_CANCEL_REQUESTED,
                        TASK_CANCELLED,
                        Ordering::AcqRel,
                        Ordering::Acquire,
                    );
                    return false;
                }
                TASK_RUNNING => return true,
                _ => return false,
            }
        }
    }

    pub fn finish(&self, outcome: TaskOutcome) -> TaskOutcome {
        match outcome {
            TaskOutcome::Failed(error) => {
                self.state.store(
                    if error.is_cancellation() {
                        TASK_CANCELLED
                    } else {
                        TASK_FAILED
                    },
                    Ordering::Release,
                );
                TaskOutcome::Failed(error)
            }
            TaskOutcome::Completed(value, stats) => loop {
                match self.state.load(Ordering::Acquire) {
                    TASK_CANCEL_REQUESTED => {
                        self.state.store(TASK_CANCELLED, Ordering::Release);
                        return TaskOutcome::Failed(BackendError::cancellation());
                    }
                    TASK_RUNNING => {
                        if self
                            .state
                            .compare_exchange(
                                TASK_RUNNING,
                                TASK_COMPLETED,
                                Ordering::AcqRel,
                                Ordering::Acquire,
                            )
                            .is_ok()
                        {
                            return TaskOutcome::Completed(value, stats);
                        }
                    }
                    _ => return TaskOutcome::Failed(BackendError::cancellation()),
                }
            },
        }
    }
}

/// The result of one `Parallel` chunk: either it ran every index cleanly, or
